import { Bell, CheckCheck } from 'lucide-react'
import { useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { PageHeader } from '@/components/layout/PageHeader'
import { Button } from '@/components/ui/Button'
import { Card } from '@/components/ui/Card'
import { FilterChips } from '@/components/ui/FilterChips'
import { Pagination } from '@/components/ui/Pagination'
import { EmptyState, ErrorState, Skeleton } from '@/components/ui/States'
import { Tabs } from '@/components/ui/Tabs'
import { NotificationItem } from '@/features/notifications/NotificationItem'
import { announceNotificationsChanged } from '@/features/notifications/notificationEvents'
import { NOTIFICATION_META } from '@/features/notifications/notificationMeta'
import { useAsync } from '@/hooks/useAsync'
import { usePagination } from '@/hooks/usePagination'
import { useViewer } from '@/hooks/useSession'
import { useToast } from '@/hooks/useToast'
import { services } from '@/services'
import type { AppNotification, NotificationCategory } from '@/types/notification'

const CATEGORIES = Object.keys(NOTIFICATION_META) as NotificationCategory[]

/** Groups by recency: today, this week, earlier. */
function groupLabel(iso: string, now = new Date()) {
  const date = new Date(iso)
  const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime()
  if (date.getTime() >= startOfToday) return 'Today'
  if (date.getTime() >= startOfToday - 6 * 86400000) return 'Earlier this week'
  return 'Older'
}

/** Notification centre for buyers and sellers. Everything here is generated by the platform or HeyCileng. */
export function NotificationsPage() {
  const navigate = useNavigate()
  const { toast } = useToast()
  const { user } = useViewer()
  // Keyed by account: buyer and seller areas share this page component.
  const { data, loading, error, reload, setData } = useAsync(() => services.notifications.list(), `notifications-${user.id}`)
  const [view, setView] = useState<'all' | 'unread'>('all')
  const [categories, setCategories] = useState<NotificationCategory[]>([])

  const all = useMemo(() => data ?? [], [data])
  const unread = all.filter((n) => !n.read).length
  const filtered = useMemo(
    () => all.filter((n) => (view === 'all' || !n.read) && (categories.length === 0 || categories.includes(n.category))),
    [all, view, categories],
  )
  const pagination = usePagination(filtered, 10, `${view}|${categories.join(',')}`)

  const open = (n: AppNotification) => {
    void services.notifications.markRead(n.id).then(announceNotificationsChanged)
    setData((list) => (list ?? []).map((x) => (x.id === n.id ? { ...x, read: true } : x)))
    if (n.href) navigate(n.href)
  }

  const markAll = async () => {
    await services.notifications.markAllRead()
    announceNotificationsChanged()
    setData((list) => (list ?? []).map((n) => ({ ...n, read: true })))
    toast({ tone: 'success', title: 'All notifications marked as read', duration: 2500 })
  }

  // Group the current page under date headings.
  const groups = pagination.pageItems.reduce<{ label: string; items: AppNotification[] }[]>((acc, n) => {
    const label = groupLabel(n.createdAt)
    const last = acc[acc.length - 1]
    if (last?.label === label) last.items.push(n)
    else acc.push({ label, items: [n] })
    return acc
  }, [])

  return (
    <>
      <PageHeader
        title="Notifications"
        description="Order, delivery, listing and match updates from HeyCileng. Buyers and sellers never message each other directly."
        actions={
          <Button variant="outline" leftIcon={<CheckCheck className="size-4" />} onClick={() => void markAll()} disabled={unread === 0}>
            Mark all as read
          </Button>
        }
      />

      <div className="mb-5 flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
        <Tabs
          label="Show"
          variant="pill"
          value={view}
          onChange={setView}
          items={[
            { value: 'all', label: 'All', count: all.length },
            { value: 'unread', label: 'Unread', count: unread },
          ]}
        />
        <FilterChips
          label="Category"
          allLabel="All types"
          multiple
          options={CATEGORIES.map((c) => ({ value: c, label: NOTIFICATION_META[c].label, count: all.filter((n) => n.category === c).length }))}
          value={categories}
          onChange={setCategories}
        />
      </div>

      {loading && !data ? (
        <Skeleton className="h-80 w-full rounded-xl" />
      ) : error ? (
        <ErrorState description={error.message} onRetry={reload} />
      ) : filtered.length === 0 ? (
        <Card>
          <EmptyState
            icon={<Bell />}
            title={view === 'unread' ? 'You’re all caught up' : 'No notifications here'}
            description={all.length === 0 ? 'Updates about your orders, listings and matches will appear here.' : 'Try another filter.'}
          />
        </Card>
      ) : (
        <div className="space-y-6">
          {groups.map((group) => (
            <section key={group.label} aria-label={group.label}>
              <h2 className="mb-2 px-1 font-sans text-xs font-semibold tracking-[0.12em] text-subtle uppercase">{group.label}</h2>
              <Card className="divide-y divide-border p-1.5">
                {group.items.map((n) => (
                  <NotificationItem key={n.id} notification={n} onOpen={open} />
                ))}
              </Card>
            </section>
          ))}
          {pagination.pageCount > 1 && (
            <Pagination
              page={pagination.page}
              pageCount={pagination.pageCount}
              onPageChange={pagination.setPage}
              rangeStart={pagination.rangeStart}
              rangeEnd={pagination.rangeEnd}
              total={pagination.total}
            />
          )}
        </div>
      )}
    </>
  )
}
